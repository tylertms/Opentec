size_t usb_compatibility_report_descriptor_encode(
    UsbInputReportMode mode, uint8_t output[USB_COMPATIBILITY_REPORT_DESCRIPTOR_MAX_SIZE],
    size_t capacity) {
    const uint8_t *descriptor;
    size_t size;

    switch (mode) {
    case USB_INPUT_REPORT_MODE_FANATEC_COMPATIBILITY:
        descriptor = fanatec_compatibility;
        size = sizeof(fanatec_compatibility);
        break;
    case USB_INPUT_REPORT_MODE_DRIVING_FORCE_EX:
        descriptor = driving_force_ex;
        size = sizeof(driving_force_ex);
        break;
    case USB_INPUT_REPORT_MODE_DRIVING_FORCE_PRO:
        descriptor = driving_force_pro;
        size = sizeof(driving_force_pro);
        break;
    case USB_INPUT_REPORT_MODE_G27:
        descriptor = g27;
        size = sizeof(g27);
        break;
    default:
        return 0;
    }

    if (output == NULL || capacity < size) {
        return 0;
    }
    memcpy(output, descriptor, size);
    return size;
}
